const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const MVR = {};
vm.runInNewContext(fs.readFileSync(__dirname + "/js/yaml.js", "utf8"), { window: { MVR } });
const y = MVR.yaml.parse("PatientName: Doe\nAnatomicRegion:\n  display: Knee\n  code: 'T-1'\nNotes:\nAge: 42\n");
assert.equal(y.PatientName, "Doe");
assert.deepEqual({ ...y.AnatomicRegion }, { display: "Knee", code: "T-1" });
assert.equal(y.Notes, null, "bare key is an empty value, not {}");
assert.equal(y.Age, 42);
const p = MVR.yaml.parse("__proto__:\n  polluted: 1\nName: x\n");
assert.equal(Object.getPrototypeOf(p), Object.getPrototypeOf(y), "__proto__ key keeps the prototype");
assert.deepEqual(Object.keys(p), ["Name"], "__proto__ children are dropped, not hoisted");
assert.equal(p.polluted, undefined);
const ids = MVR.yaml.parse("PatientID: 0012345\nZero: 0\nNeg: -7\nBig: 12345678901234567890\nTime: 083000\n");
assert.equal(ids.PatientID, "0012345", "leading zeros kept");
assert.equal(ids.Zero, 0);
assert.equal(ids.Neg, -7);
assert.equal(ids.Big, "12345678901234567890", "unsafe integer kept as text");
assert.equal(ids.Time, "083000");
console.log("YAML subset: passed");
